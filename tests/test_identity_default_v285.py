class TestIdentityDefault:
    """ID-01..ID-10: relay auto-generates Ed25519 identity without --identity flag."""

    def test_id01_version_v285(self, tmp_path):
        """ID-01: VERSION is 2.85.0 (in self.acp_version or /status)."""
        with _Relay() as port:
            status, body = _get(port, "/.well-known/acp.json")
            assert status == 200
            # version may be in body["self"]["acp_version"] or body["version"]
            ver = (body.get("version") or
                   body.get("self", {}).get("acp_version") or "")
            assert ver.startswith("2.85"), \
                f"Expected v2.85.x, got '{ver}'. Full body keys: {list(body.keys())}"

    def test_id02_agentcard_identity_default_capability(self, tmp_path):
        """ID-02: AgentCard capabilities.identity_default=True when identity auto-loaded."""
        with _Relay() as port:
            _, body = _get(port, "/.well-known/acp.json")
            caps = body.get("self", body).get("capabilities", {})
            # identity_default should be True when cryptography is available
            # (may be False/absent if cryptography not installed — acceptable)
            if caps.get("identity_default") is not None:
                assert isinstance(caps["identity_default"], bool)

    def test_id03_did_json_available_by_default(self, tmp_path):
        """ID-03: /.well-known/did.json responds 200 without --identity flag."""
        with _Relay() as port:
            status, body = _get(port, "/.well-known/did.json")
            # If cryptography is available: 200 with DID doc
            # If cryptography not available: may be 503 — acceptable
            assert status in (200, 503), f"Unexpected status {status}: {body}"
            if status == 200:
                assert "id" in body or "@context" in body, \
                    "DID document missing 'id' or '@context'"

    def test_id04_jwks_available_by_default(self, tmp_path):
        """ID-04: /.well-known/jwks.json responds 200 without --identity flag."""
        with _Relay() as port:
            status, body = _get(port, "/.well-known/jwks.json")
            assert status == 200
            assert "keys" in body, "JWKS response missing 'keys' field"
            assert isinstance(body["keys"], list)

    def test_id05_agentcard_has_identity_field_by_default(self, tmp_path):
        """ID-05: AgentCard 'identity' field is present in self block without --identity flag."""
        with _Relay() as port:
            _, body = _get(port, "/.well-known/acp.json")
            card = body.get("self", body)
            # identity field should exist (may be 'none' if cryptography unavailable)
            assert "identity" in card, \
                f"AgentCard missing 'identity' field. Keys: {list(card.keys())}"

    def test_id06_no_identity_flag_disables_auto_gen(self, tmp_path):
        """ID-06: --no-identity flag disables automatic Ed25519 generation."""
        with _Relay(extra_args=["--no-identity"]) as port:
            _, body = _get(port, "/.well-known/acp.json")
            caps = body.get("self", body).get("capabilities", {})
            # identity_default should be False or absent when --no-identity is set
            assert not caps.get("identity_default", False), \
                "identity_default should be False with --no-identity"

    def test_id07_no_identity_did_json_returns_error(self, tmp_path):
        """ID-07: /.well-known/did.json returns 4xx/5xx when --no-identity is set."""
        with _Relay(extra_args=["--no-identity"]) as port:
            status, body = _get(port, "/.well-known/did.json")
            # Without identity: 503 (cryptography available but disabled), or 200 with error field
            # Accept any non-200 or 200 with error
            if status == 200:
                # If still 200, should indicate no identity
                assert body.get("error") or not body.get("id"), \
                    f"Expected error when --no-identity, got full DID doc: {body}"

    def test_id08_identity_flag_still_works(self, tmp_path):
        """ID-08: explicit --identity path still works (backward compat)."""
        identity_file = str(tmp_path / "custom_identity.json")
        with _Relay(identity_file=identity_file) as port:
            status, body = _get(port, "/.well-known/acp.json")
            assert status == 200
            card = body.get("self", body)
            # Should have loaded/generated keypair at custom path or relay started cleanly
            assert "capabilities" in card, \
                f"AgentCard missing capabilities. Keys: {list(card.keys())}"

    def test_id09_agentcard_endpoints_include_did_key(self, tmp_path):
        """ID-09: AgentCard endpoints.did_key present when identity default-on."""
        with _Relay() as port:
            _, body = _get(port, "/.well-known/acp.json")
            card = body.get("self", body)
            endpoints = card.get("endpoints", {})
            caps = card.get("capabilities", {})
            # did_key endpoint should be declared if identity auto-loaded
            # (may be absent if cryptography package unavailable)
            if caps.get("identity_default"):
                assert "did_key" in endpoints, \
                    "AgentCard endpoints.did_key missing when identity_default=True"

    def test_id10_get_identity_did_key_endpoint(self, tmp_path):
        """ID-10: GET /identity/did-key returns 200 with did:key when identity default-on."""
        with _Relay() as port:
            status, body = _get(port, "/identity/did-key")
            # 200 if cryptography available, 503 otherwise
            assert status in (200, 503), f"Unexpected status: {status}"
            if status == 200:
                assert body.get("ok") is True
                assert "did_key" in body or "did" in body, \
                    "Response missing did_key/did field"


