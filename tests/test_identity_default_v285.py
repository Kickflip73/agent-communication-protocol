def _free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def _http(http_port: int, path: str, method: str = "GET", body=None, timeout: int = 10):
    """HTTP helper using urllib (handles 4xx/5xx via HTTPError)."""
    url = f"http://127.0.0.1:{http_port}{path}"
    data = json.dumps(body).encode() if body is not None else None
    headers = {"Content-Type": "application/json"} if data else {}
    req = urllib.request.Request(url, data=data, method=method, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return json.loads(r.read()), r.status
    except urllib.error.HTTPError as e:
        try:
            return json.loads(e.read()), e.code
        except Exception:
            return {}, e.code
    except Exception as exc:
        raise RuntimeError(f"HTTP {method} {path} failed: {exc}") from exc


def _get(http_port: int, path: str):
    """Returns (status_code, body_dict)."""
    body, status = _http(http_port, path, "GET")
    return status, body


def _post(http_port: int, path: str, payload: dict):
    """Returns (status_code, body_dict)."""
    body, status = _http(http_port, path, "POST", payload)
    return status, body


def _wait_for(fn, timeout=15, interval=0.3):
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            if fn():
                return True
        except Exception:
            pass
        time.sleep(interval)
    return False


class _Relay:
    """Context manager: spin up acp_relay.py, yield http_port, teardown.

    acp_relay.py uses:
      --port N   → WebSocket port N
      HTTP API   → port N + 100
    """

    def __init__(self, extra_args=None, identity_file=None):
        self.extra_args = extra_args or []
        self.identity_file = identity_file
        self.ws_port = _free_port()
        self.http_port = self.ws_port + 100
        self.proc = None

    def __enter__(self):
        cmd = [
            sys.executable, RELAY,
            "--port", str(self.ws_port),
            "--local-only",
        ] + self.extra_args
        if self.identity_file:
            cmd += ["--identity", self.identity_file]
        self.proc = subprocess.Popen(
            cmd,
            stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        )
        def _is_ready():
            try:
                status, body = _get(self.http_port, "/status")
                return status in (200, 204)
            except Exception:
                return False

        ready = _wait_for(_is_ready, timeout=20, interval=0.4)
        if not ready:
            self.proc.kill()
            out, err = self.proc.communicate()
            raise RuntimeError(
                f"Relay did not start on HTTP port {self.http_port}. "
                f"stderr: {err.decode()[-500:]}"
            )
        return self.http_port

    def __exit__(self, *_):
        if self.proc:
            self.proc.terminate()
            try:
                self.proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                self.proc.kill()


